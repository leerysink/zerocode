def _db_facts(db) -> str:
    """meta["database"] → dev/prod 库名与用户各一行事实；缺失或形态异常则降级为空（不抛）。

    app.json 本无口令，列库名/用户是安全事实，且与「连接串由平台注入」的约束同行陈述。
    """
    lines = []
    if isinstance(db, dict):
        for env in ("dev", "prod"):
            entry = db.get(env)
            if not isinstance(entry, dict):
                continue
            name, user = entry.get("name"), entry.get("user")
            if not name:
                continue
            seg = f"- {env} 库：{name}"
            if user:
                seg += f"（用户 {user}）"
            lines.append(seg)
    if not lines:
        return ""
    return ("本应用数据库（app.json 不含口令，连接串一律由平台注入环境变量，代码不得硬编码；"
            "库名与用户仅供理解，代码与 SQL 不得引用库名/用户名）：\n"
            + "\n".join(lines) + "\n")

def build_app_contract(root: Path) -> str | None:
    """读 root/app.json 渲染契约文本；任何损坏/异常形态（缺文件、非法 JSON、顶层非对象、
    字段形态错乱、读取 IO 错误）都不向调用方抛异常，统一返回 None 表示「不注入」。
    准入闸门：仅平台清单（schema=zc-app/1 且 slug 非空）才注入，外来 app.json 与残缺字段静默跳过。"""
    try:
        f = root / "app.json"
        if not f.is_file():
            return None
        meta = json.loads(f.read_text(encoding="utf-8"))
        if not isinstance(meta, dict):          # 合法 JSON 但顶层非对象（如 [1,2]、"x"）
            logger.warning("app.json 顶层不是对象，契约未注入: %s", root)
            return None
        if meta.get("schema") != "zc-app/1" or not meta.get("slug"):
            logger.warning("app.json 非 zc-app/1 清单或缺 slug，契约未注入: %s", root)
            return None
        stack = meta.get("stack", "")
        ports = meta.get("ports")
        health = meta.get("health")
        if not isinstance(ports, dict):
            ports = {}
        if not isinstance(health, dict):
            health = {}
        no_db = stack in _NO_DB_STACKS
        return (
            f"\n\n【应用契约】当前工作区是 zerocode 应用工程「{meta.get('name')}」（{meta.get('slug')}，"
            f"{STACK_LABEL.get(stack, stack)}，dev 预览端口 {ports.get('dev')}）。\n"
            # 库事实对 static 不注入：纯前端够不着 PG，列出库名只会邀请模型去设计「假装能连库」的前端
            + ("" if no_db else _db_facts(meta.get("database"))) +
            (_STATIC_DIR_TEXT if no_db else
             "1) 目录：frontend/（Vue3+ant-design-vue）、backend/（后端工程，static 栈无）、"
             "schema/（结构真相）、sqlchange/（数据轨：顶层公共段 + dev/ 与 prod/ 两个环境段）、deploy/、"
             "docs/（应用过程文档：adr/ 存需求决策、specs/ 存计划，不进市场包）。\n") +
            "2) 技术栈与版本以现有脚手架为准，只能追加依赖，不得替换或降级已锁定版本。\n"
            + (_STATIC_DATA_TEXT if no_db else
               "3) 数据库变更走双轨："
            "**改表结构 → 编辑 `schema/schema.sql` 的目标态**（只写幂等可重放 DDL："
            "CREATE TABLE IF NOT EXISTS、逐列 ALTER TABLE ADD COLUMN IF NOT EXISTS、"
            "CREATE INDEX IF NOT EXISTS；不写数据、不写 DROP、不改列类型）；"
            "**补列红线**：schema.sql 每次预览与发布都全量重放，给已有数据的表补列时裸写 `NOT NULL` "
            "必被 PG 拒（contains null values），且 fold 不记账 → 之后每次重启红在同一行、栈永久起不来；"
            "新列要么带 `DEFAULT`（要求唯一时默认值取 `gen_random_uuid()::text`，常量默认值会让存量行撞唯一索引），"
            "要么只补可空列、把值交给数据轨回填，且 `ALTER COLUMN ... SET NOT NULL` 不得写进 schema.sql"
            "（fold 先于数据轨，同一次重启会跑在回填之前）；"
            "**唯一索引红线**：给已有数据的表加 `CREATE UNIQUE INDEX`（或唯一约束）前，先确认存量值没有重复——"
            "fold 先于数据轨，同一次启动里建索引一定跑在清理之前，撞重复就红在 "
            "`could not create unique index`（`DETAIL: Key (col)=() is duplicated.` 里的 `()` 是空串不是 NULL："
            "普通唯一索引允许多个 NULL，但不允许多个空串）。存量可能有重复时拆两步："
            "本版只把清理/回填写进数据轨，下一个版本再加唯一索引；"
            "「可选」的列不要用常量默认值（尤其 `''`）占位，写成可空列、未填就是 NULL；"
            "写后端查询前先读 `schema/schema.sql` 取权威结构，勿猜表/列/索引。"
            "**数据变更（种子/回填/刷值）→ 追加 `sqlchange/D<YYYYMMDD>_<两位序号>_<说明>.sql`**"
            "（写前查看目录取下一个序号；一个文件一个逻辑变更；一经应用不得修改也不得删除，只能追加；"
            "幂等，种子用 INSERT ... ON CONFLICT DO NOTHING）。"
            "**数据轨分三段**：顶层 `sqlchange/` 是公共段（dev 与 prod 两库都跑），"
            "`sqlchange/dev/` 只进 dev 库，`sqlchange/prod/` 只进 prod 库，一次执行跑「公共段 + 本环境段」。"
            "位置按数据用途定：**参考数据**（菜单、字典、角色授权、系统参数）线上必须有——两边同内容就只写顶层一份，"
            "取值要分叉才在 `dev/` 与 `prod/` 各写一份（两份同名合法，记账按相对 `sqlchange/` 的路径区分）；"
            "**演示数据**（测试用户、样例订单、凑数的 demo 内容）只写 `sqlchange/dev/`，别把它带上生产。"
            "写 prod 段之前先用 `db_query`（env=prod，只读）查线上现状，据此定幂等写法和要不要成对；"
            "平台不会替你补 prod 段——漏写线上种子就是线上缺数据，发布时没有硬闸门会拦你。\n"
            "删表/删列/改名/改列类型属破坏性：分两步走（先加新列并双写并发布，下个版本才从 schema.sql "
            "移除旧列、并在数据轨补回填），发布前的结构 diff 会拦住未走两步的破坏性变更；"
            "若本应用已上架商店，你的改动会决定别人能不能升级，宁可分两步；"
            "代码里不得出现建表/改表语句，不得硬编码数据库连接；"
            "数据轨 sqlchange 文件在单事务内执行，schema.sql 建索引写普通 CREATE INDEX IF NOT EXISTS，"
            "不得使用 CREATE INDEX CONCURRENTLY。\n")
            + (_STATIC_ENV_TEXT if no_db else
               f"4) 后端从环境变量读取 {ENV_HINT.get(stack, '平台注入的环境变量')}；必须保持 /api 前缀与 health 接口"
               f"（{health.get('backend', '')}）可用。\n")
            + "5) 前端页面用 ant-design-vue，中文界面，表格用 columns+bodyCell 模式，弹窗表单 label 宽 120px 右对齐。\n"
            "6) deploy/ 与 app.json 由平台管理，禁止读写。\n"
            "7) 完成功能后告知用户：可点「预览」查看效果，正式使用请点「发布」。"
            + STACK_EXTRA.get(stack, ""))
    except Exception:
        logger.warning("app.json 读取或解析失败，契约未注入: %s", root)
        return None
