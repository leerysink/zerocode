-- {{APP_NAME}}（{{SLUG}}）结构真相 —— 声明式目标态快照，可重放、永不 DROP
-- 平台在每次预览与发布前全量重放本文件（结构不进账本，只作投影），因此：
--   · 只写 CREATE TABLE IF NOT EXISTS / 逐列 ALTER TABLE ADD COLUMN IF NOT EXISTS
--        / CREATE INDEX IF NOT EXISTS / COMMENT ON；
--   · 不写数据、不写 DROP、不改列类型（破坏性变更走两步法，见 ../sqlchange/README.md）；
--   · 改结构 = 编辑本文件的目标态；改数据 = 往 ../sqlchange 追加 D 文件。
-- 基座 11 张 sys_* 表不得改名、不得删列（会连带打断登录、侧栏与操作日志）；
-- 列定义与后端实体逐列对齐，写查询前先读本文件取权威的列与索引，勿猜结构。
-- 数据库：PostgreSQL 16（需 12 及以上：依赖 identity 序列、部分唯一索引、CREATE INDEX IF NOT EXISTS）。
-- =====================================================

-- 1. 部门表（数据权限载体）
CREATE TABLE IF NOT EXISTS sys_dept (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id   bigint       NOT NULL DEFAULT 0,
    ancestors   varchar(500) NOT NULL DEFAULT '0',
    dept_name   varchar(64)  NOT NULL,
    order_num   integer      NOT NULL DEFAULT 0,
    leader      varchar(32),
    phone       varchar(20),
    status      smallint     NOT NULL DEFAULT 1,
    deleted     smallint     NOT NULL DEFAULT 0,
    create_time timestamp    NOT NULL DEFAULT now(),
    update_time timestamp    NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_dept_parent_id ON sys_dept(parent_id);
CREATE INDEX IF NOT EXISTS idx_dept_name      ON sys_dept(dept_name);
COMMENT ON TABLE  sys_dept             IS '部门表';
COMMENT ON COLUMN sys_dept.ancestors   IS '祖级路径，形如 0,1, ；仅用于树展示与移动子树，不参与权限 SQL';
COMMENT ON COLUMN sys_dept.status      IS '状态: 1=正常 0=停用';
COMMENT ON COLUMN sys_dept.deleted     IS '逻辑删除: 0=未删 1=已删';

-- 2. 系统用户表
CREATE TABLE IF NOT EXISTS sys_user (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username    varchar(50)  NOT NULL,
    password    varchar(100) NOT NULL,
    nickname    varchar(50),
    dept_id     bigint,
    phone       varchar(20),
    email       varchar(100),
    status      smallint     NOT NULL DEFAULT 1,
    create_time timestamp    NOT NULL DEFAULT now(),
    update_time timestamp    NOT NULL DEFAULT now(),
    deleted     smallint     NOT NULL DEFAULT 0
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_username ON sys_user(username) WHERE deleted = 0;
CREATE INDEX IF NOT EXISTS idx_user_dept_id   ON sys_user(dept_id);
COMMENT ON TABLE  sys_user         IS '系统用户表';
COMMENT ON COLUMN sys_user.dept_id IS '所属部门ID，可为空表示未分配部门';
COMMENT ON COLUMN sys_user.status  IS '状态: 1=正常 0=停用';

-- 3. 角色表
CREATE TABLE IF NOT EXISTS sys_role (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_name   varchar(50) NOT NULL,
    role_key    varchar(50) NOT NULL,
    data_scope  smallint    NOT NULL DEFAULT 1,
    sort        integer     NOT NULL DEFAULT 0,
    status      smallint    NOT NULL DEFAULT 1,
    remark      varchar(255),
    create_time timestamp   NOT NULL DEFAULT now(),
    update_time timestamp   NOT NULL DEFAULT now(),
    deleted     smallint    NOT NULL DEFAULT 0
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_role_key ON sys_role(role_key) WHERE deleted = 0;
COMMENT ON TABLE  sys_role IS '角色表';
COMMENT ON COLUMN sys_role.data_scope IS '数据范围: 1=全部 2=本部门 3=本部门及以下 4=自定义';

-- 4. 用户-角色关联表
CREATE TABLE IF NOT EXISTS sys_user_role (
    user_id bigint NOT NULL,
    role_id bigint NOT NULL,
    PRIMARY KEY (user_id, role_id)
);
CREATE INDEX IF NOT EXISTS idx_user_role_role_id ON sys_user_role(role_id);
COMMENT ON TABLE sys_user_role IS '用户-角色关联表';

-- 5. 角色-部门关联表（自定义数据权限，data_scope=4 时生效）
CREATE TABLE IF NOT EXISTS sys_role_dept (
    role_id bigint NOT NULL,
    dept_id bigint NOT NULL,
    PRIMARY KEY (role_id, dept_id)
);
COMMENT ON TABLE sys_role_dept IS '角色-部门关联表（data_scope=4 自定义数据权限时生效）';

-- 6. 菜单表
CREATE TABLE IF NOT EXISTS sys_menu (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id   bigint      NOT NULL DEFAULT 0,
    menu_name   varchar(50) NOT NULL,
    menu_type   char(1)     NOT NULL,
    path        varchar(200),
    component   varchar(255),
    permission  varchar(100),
    icon        varchar(100),
    sort        integer     NOT NULL DEFAULT 0,
    visible     smallint    NOT NULL DEFAULT 1,
    status      smallint    NOT NULL DEFAULT 1,
    create_time timestamp   NOT NULL DEFAULT now()
);
COMMENT ON TABLE  sys_menu            IS '菜单表';
COMMENT ON COLUMN sys_menu.menu_type  IS '菜单类型: M=目录 C=菜单 F=按钮';
COMMENT ON COLUMN sys_menu.permission IS '权限标识，随登录信息接口下发给前端';

-- 7. 角色-菜单关联表
CREATE TABLE IF NOT EXISTS sys_role_menu (
    role_id bigint NOT NULL,
    menu_id bigint NOT NULL,
    PRIMARY KEY (role_id, menu_id)
);
COMMENT ON TABLE sys_role_menu IS '角色-菜单关联表';

-- 8. 字典类型表
CREATE TABLE IF NOT EXISTS sys_dict_type (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dict_name   varchar(100) NOT NULL,
    dict_type   varchar(100) NOT NULL,
    status      smallint     NOT NULL DEFAULT 1,
    remark      varchar(255),
    create_time timestamp    NOT NULL DEFAULT now(),
    update_time timestamp    NOT NULL DEFAULT now(),
    deleted     smallint     NOT NULL DEFAULT 0
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_dict_type ON sys_dict_type(dict_type) WHERE deleted = 0;
COMMENT ON TABLE sys_dict_type IS '字典类型表';

-- 9. 字典数据表
CREATE TABLE IF NOT EXISTS sys_dict_data (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dict_type   varchar(100) NOT NULL,
    dict_label  varchar(100) NOT NULL,
    dict_value  varchar(100) NOT NULL,
    sort        integer      NOT NULL DEFAULT 0,
    status      smallint     NOT NULL DEFAULT 1,
    remark      varchar(255),
    create_time timestamp    NOT NULL DEFAULT now(),
    update_time timestamp    NOT NULL DEFAULT now(),
    deleted     smallint     NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS idx_dict_data_type ON sys_dict_data(dict_type);
COMMENT ON TABLE sys_dict_data IS '字典数据表';

-- 10. 操作日志表（列集合对齐 entity/SysOperLog）
CREATE TABLE IF NOT EXISTS sys_oper_log (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title          varchar(50)  DEFAULT '',
    business_type  integer      DEFAULT 0,
    method         varchar(200) DEFAULT '',
    request_method varchar(10)  DEFAULT '',
    oper_url       varchar(255) DEFAULT '',
    oper_ip        varchar(50)  DEFAULT '',
    oper_location  varchar(100) DEFAULT '',
    oper_param     text,
    json_result    text,
    status         smallint     DEFAULT 1,
    error_msg      text         DEFAULT '',
    oper_user_id   bigint,
    oper_user_name varchar(50)  DEFAULT '',
    cost_time      bigint       DEFAULT 0,
    create_time    timestamp    NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_oper_business_type ON sys_oper_log(business_type);
CREATE INDEX IF NOT EXISTS idx_oper_user_id       ON sys_oper_log(oper_user_id);
CREATE INDEX IF NOT EXISTS idx_oper_create_time   ON sys_oper_log(create_time);
COMMENT ON TABLE  sys_oper_log      IS '操作日志表';
COMMENT ON COLUMN sys_oper_log.status IS '操作状态: 1=成功 0=失败';

-- 11. 登录日志表（列集合对齐 entity/SysLoginLog）
CREATE TABLE IF NOT EXISTS sys_login_log (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_name      varchar(50)  DEFAULT '',
    user_id        bigint,
    ipaddr         varchar(50)  DEFAULT '',
    login_location varchar(100) DEFAULT '',
    browser        varchar(100) DEFAULT '',
    os             varchar(100) DEFAULT '',
    status         smallint     DEFAULT 1,
    msg            varchar(255) DEFAULT '',
    login_type     smallint     DEFAULT 1,
    login_time     timestamp    NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_login_status ON sys_login_log(status);
CREATE INDEX IF NOT EXISTS idx_login_time   ON sys_login_log(login_time);
COMMENT ON TABLE  sys_login_log            IS '登录日志表';
COMMENT ON COLUMN sys_login_log.status     IS '状态: 1=成功 0=失败';
COMMENT ON COLUMN sys_login_log.login_type IS '日志类型: 1=登录 2=登出';

